CREATE TABLE CLIENTE
(
    ID_CLI      NUMBER (9)  GENERATED BY DEFAULT AS IDENTITY (START WITH 1 NOCACHE) NOT NULL ,
    NOME_CLI    VARCHAR2 (100) ,
    DATA_CADAST DATE
)
;

COMMENT ON COLUMN CLIENTE.ID_CLI IS 'Identificador do Cliente'
;

COMMENT ON COLUMN CLIENTE.NOME_CLI IS 'Nome do Cliente'
;

COMMENT ON COLUMN CLIENTE.DATA_CADAST IS 'Data do Cadastro do Cliente'
;

ALTER TABLE CLIENTE
    ADD CONSTRAINT CLIENTE_PK PRIMARY KEY ( ID_CLI ) ;

CREATE TABLE EVIDENCIA
(
    ID_EVID         NUMBER (9) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 NOCACHE) NOT NULL ,
    TIPO_EVID       VARCHAR2 (20) ,
    INSIGHT_ID_INSI NUMBER (9)  NOT NULL
)
;

COMMENT ON COLUMN EVIDENCIA.ID_EVID IS 'Identificador de Evidencia'
;

COMMENT ON COLUMN EVIDENCIA.TIPO_EVID IS 'Tipo de evidencia(Sentimento, Risco, Oportunidade, Problema, Geral)'
;

COMMENT ON COLUMN EVIDENCIA.INSIGHT_ID_INSI IS 'Identificador de Insight'
;

ALTER TABLE EVIDENCIA
    ADD CONSTRAINT EVIDENCIA_PK PRIMARY KEY ( ID_EVID ) ;

CREATE TABLE INSIGHT
(
    ID_INSI         NUMBER (9)  GENERATED BY DEFAULT AS IDENTITY (START WITH 1 NOCACHE) NOT NULL ,
    TIPO_INSI       VARCHAR2 (30) ,
    DESCRICAO_INSI  VARCHAR2 (500) ,
    SCORE_INSI      NUMBER (5,2) ,
    PONT_SENTIMENTO NUMBER (5,2) ,
    REUNIAO_ID_REUN NUMBER (9)  NOT NULL
)
;

COMMENT ON COLUMN INSIGHT.ID_INSI IS 'Identificador do insight'
;

COMMENT ON COLUMN INSIGHT.TIPO_INSI IS 'Tipo do insight'
;

COMMENT ON COLUMN INSIGHT.DESCRICAO_INSI IS 'Descrição do insight'
;

COMMENT ON COLUMN INSIGHT.SCORE_INSI IS 'Pontuação calculada'
;

COMMENT ON COLUMN INSIGHT.PONT_SENTIMENTO IS 'Pontuação geral de sentimento da reunião'
;

ALTER TABLE INSIGHT
    ADD CONSTRAINT INSIGHT_PK PRIMARY KEY ( ID_INSI ) ;

